def _get_player_id() -> str:
    """Get the authenticated GitHub username as player ID.

    Returns the GitHub username from the OAuth token, or a default
    if authentication is not configured.
    """
    token = get_access_token()
    if token is None:
        return "anonymous"

    # The GitHubProvider includes user info in JWT claims
    # Try to get the GitHub username from claims
    claims = token.claims or {}

    # GitHubProvider should include 'login' or 'sub' with the username
    username = claims.get("login") or claims.get("sub") or claims.get("preferred_username")
    if username:
        return username

    # Fallback to client_id if no username in claims
    return token.client_id or "anonymous"


async def _get_npc_mcp_client() -> Optional[str]:
    """Get custom MCP client name for NPC tokens from Redis.

    Checks if the current token is an NPC token and looks up the
    custom mcp_client_name stored in Redis during token generation.

    Returns:
        Custom MCP client name if NPC with override, None otherwise.
    """
    token = get_access_token()
    if token is None:
        logger.debug("_get_npc_mcp_client: no access token")
        return None

    claims = token.claims or {}

    # Check if this is an NPC token
    if not claims.get("npc"):
        logger.debug("_get_npc_mcp_client: not an NPC token (npc claim missing)")
        return None

    # Get username and race_id from claims to build Redis key
    username = claims.get("login") or claims.get("sub")
    race_id = claims.get("race_id")
    logger.debug(f"_get_npc_mcp_client: NPC token - username={username}, race_id={race_id}")

    if not username or not race_id:
        logger.warning(
            f"_get_npc_mcp_client: missing username or race_id in NPC claims: {claims}"
        )
        return None

    # Look up token data in Redis
    try:
        redis_client = aioredis.Redis(host=REDIS_HOST, port=REDIS_PORT)
        try:
            token_key = f"npc:token:{username}:{race_id}"
            logger.debug(f"_get_npc_mcp_client: looking up Redis key {token_key}")
            token_data_raw = await redis_client.get(token_key)

            if token_data_raw:
                token_data = json.loads(token_data_raw)
                mcp_client_name = token_data.get("mcp_client_name")
                logger.info(
                    f"_get_npc_mcp_client: found custom name '{mcp_client_name}' for {username}"
                )
                return mcp_client_name
            else:
                logger.warning(
                    f"_get_npc_mcp_client: Redis key {token_key} not found"
                )
        finally:
            await redis_client.aclose()
    except Exception as e:
        logger.error(f"_get_npc_mcp_client: Redis error: {e}")

    return None


async def _get_mcp_client(ctx: Context) -> str:
    """Get the MCP client name from NPC token data or session params.

    For NPC tokens, looks up custom mcp_client_name from Redis.
    For regular users, returns the client name from MCP initialize handshake.

    Returns:
        Client name (e.g., "Mistral Vibe", "claude-code", "cursor") or "unknown".
    """
    # Check for NPC custom client name first
    npc_client = await _get_npc_mcp_client()
    if npc_client:
        return npc_client

    # Fall back to session client info for regular users
    try:
        if (
            ctx.request_context
            and ctx.request_context.session.client_params
            and ctx.request_context.session.client_params.clientInfo
        ):
            return ctx.request_context.session.client_params.clientInfo.name
    except Exception:
        pass
    return "unknown"


def _get_auth_headers() -> dict[str, str]:
    """Get authorization headers for backend requests.

    Returns headers with the access token for backend authentication.
    """
    token = get_access_token()
    if token is None or not token.token:
        return {}

    # Pass the token to the backend for validation
    return {"Authorization": f"Bearer {token.token}"}


async def _backend_request(
    method: str,
    path: str,
    json: Optional[dict] = None,
) -> dict:
    """Make authenticated request to backend.

    Args:
        method: HTTP method (GET, POST, etc.)
        path: URL path (e.g., "/lobbies")
        json: Optional JSON body

    Returns:
        Response JSON as dict
    """
    headers = _get_auth_headers()

    async with httpx.AsyncClient(timeout=30.0) as client:
        response = await client.request(
            method,
            f"{BACKEND_URL}{path}",
            json=json,
            headers=headers,
        )
        response.raise_for_status()
        return response.json()


def _format_state_as_text(state: dict[str, Any], race_id: str, player_id: str) -> str:
    """Transform game state JSON to natural language using Jinja2.

    Args:
        state: Full game state from API
        race_id: The race identifier
        player_id: The player requesting the state (used to show their own data)
    """
    phase = state.get("phase", "racing")
    racers = state.get("racers", {})
    racer = racers.get(player_id, {})
    track = state.get("track", {})
    tiles = track.get("tiles", [])

    # Handle lobby phase (private races)
    if phase == "lobby":
        template = jinja_env.get_template("lobby_state.jinja2")
        return template.render(
            race_id=race_id,
            phase=phase,
            creator_id=state.get("creator_id"),
            is_host=state.get("creator_id") == player_id,
            player_id=player_id,
            racers=list(racers.keys()),
            racer_count=len(racers),
            max_racers=state.get("max_racers", 8),
        )

    # Handle matchmaking phase (public races)
    if phase == "matchmaking":
        # Calculate remaining seconds until auto-start
        remaining_seconds = 300  # Default 5 minutes
        matchmaking_ends_at = state.get("matchmaking_ends_at")
        if matchmaking_ends_at:
            try:
                ends_at = datetime.fromisoformat(matchmaking_ends_at.replace("Z", "+00:00"))
                now = datetime.now(timezone.utc)
                remaining_seconds = max(0, int((ends_at - now).total_seconds()))
            except (ValueError, TypeError):
                pass

        ready_players = state.get("ready_players", [])

        template = jinja_env.get_template("matchmaking_state.jinja2")
        return template.render(
            race_id=race_id,
            phase=phase,
            player_id=player_id,
            racers=list(racers.keys()),
            racer_count=len(racers),
            max_racers=state.get("max_racers", 8),
            ready_players=ready_players,
            remaining_seconds=remaining_seconds,
            is_ready=player_id in ready_players,
        )

    # Handle planning phase
    if phase == "planning":
        # Calculate remaining seconds until race starts
        remaining_seconds = 60  # Default fallback
        planning_ends_at = state.get("planning_ends_at")
        if planning_ends_at:
            try:
                # Parse ISO format datetime string
                ends_at = datetime.fromisoformat(planning_ends_at.replace("Z", "+00:00"))
                now = datetime.now(timezone.utc)
                remaining_seconds = max(0, int((ends_at - now).total_seconds()))
            except (ValueError, TypeError):
                pass  # Use default if parsing fails

        template = jinja_env.get_template("planning_state.jinja2")
        return template.render(
            race_id=race_id,
            phase=phase,
            creator_id=state.get("creator_id"),
            player_id=player_id,
            racers=list(racers.keys()),
            racer_count=len(racers),
            remaining_seconds=remaining_seconds,
        )

    # Handle racing/finished phases
    if not racer or not tiles:
        return str(state)

    # Calculate upcoming tiles (next 10)
    current_tile = racer.get("tile_index", 0)
    total_tiles = len(tiles)
    upcoming = []
    for i in range(1, 11):
        tile_idx = (current_tile + i) % total_tiles
        tile = tiles[tile_idx]
        upcoming.append({
            "distance_tiles": i,
            "type": tile.get("tile_type", "unknown"),
            "has_item_box": tile.get("has_item_box", False),
        })

    # Get controls for the requesting player only (private info)
    controls = racer.get("controls", {})

    # Build race positions for multi-racer display
    positions = []
    sorted_racers = sorted(
        racers.items(),
        key=lambda x: (
            -(x[1].get("current_lap", 0)),  # Higher lap first
            -(x[1].get("tile_index", 0)),   # Higher tile first
            -(x[1].get("tile_subunit", 0)), # Higher subunit first
        ),
    )
    for place, (pid, r) in enumerate(sorted_racers, 1):
        positions.append({
            "place": place,
            "player_id": pid,
            "tile": r.get("tile_index", 0),
            "lap": r.get("current_lap", 0),
            "status": r.get("status", "racing"),
        })

    template = jinja_env.get_template("state.jinja2")
    return template.render(
        race_id=race_id,
        race_clock=state.get("race_clock", "0:00"),
        max_race_clock=state.get("max_race_clock", "10:00"),
        race_status="finished" if state.get("is_finished") else "in_progress",
        phase=phase,
        player_id=player_id,
        racer_count=len(racers),
        positions=positions,
        racer={
            "position": {
                "tile": current_tile,
                "subunit": racer.get("tile_subunit", 0),
                "lap": racer.get("current_lap", 0),
            },
            "speed": racer.get("speed", 0),
            "target_speed": controls.get("target_speed", 0),
            "max_speed": 5 if racer.get("boost_seconds_remaining", 0) > 0 else 3,
            "in_drift_zone": racer.get("in_drift_zone", False),
            "drift_enabled": racer.get("drift_enabled", False),
            "on_turn_tile": racer.get("on_turn_tile", False),
            "power_up": racer.get("power_up"),
            "boost_seconds_remaining": racer.get("boost_seconds_remaining", 0),
            "status": racer.get("status", "racing"),
            "penalty_seconds_remaining": racer.get("penalty_seconds_remaining", 0),
            "finish_position": racer.get("finish_position"),
        },
        track={
            "total_tiles": total_tiles,
            "laps_required": state.get("laps_required", 3),
        },
        upcoming_tiles=upcoming,
        standings=state.get("standings", []),
    )


@mcp.tool()
async def create_lobby(ctx: Context) -> str:
    """Create a new race lobby and become the host.

    Returns:
        Lobby information including the race_id to share with other players.
        As the lobby creator, you can start the race when ready.
    """
    player_id = _get_player_id()
    mcp_client = await _get_mcp_client(ctx)

    data = await _backend_request(
        "POST",
        "/lobbies",
        json={"creator_id": player_id, "mcp_client": mcp_client},
    )

    race_id = data["race_id"]
    state = data.get("state")

    if state:
        state_text = _format_state_as_text(state, race_id, player_id)
    else:
        state_text = "Lobby created, use get_state to see current status"

    template = jinja_env.get_template("lobby_created.jinja2")
    return template.render(race_id=race_id, player_id=player_id, state=state_text)


@mcp.tool()
async def join_race(ctx: Context, race_id: Optional[str] = None) -> str:
    """Join a race. Either join an existing lobby or create a new one.

    Args:
        race_id: Optional. If provided, joins that lobby. If not, creates a new lobby.

    Returns:
        Race information and current state.
    """
    player_id = _get_player_id()
    mcp_client = await _get_mcp_client(ctx)

    if race_id:
        # Join existing lobby
        data = await _backend_request(
            "POST",
            f"/lobbies/{race_id}/join",
            json={"player_id": player_id, "mcp_client": mcp_client},
        )
        actual_race_id = race_id
        is_host = False
    else:
        # Create new lobby (becomes the host)
        data = await _backend_request(
            "POST",
            "/lobbies",
            json={"creator_id": player_id, "mcp_client": mcp_client},
        )
        actual_race_id = data.get("race_id")
        is_host = True

    state = data.get("state")

    if state:
        state_text = _format_state_as_text(state, actual_race_id, player_id)
    else:
        state_text = "Joined successfully, use get_state to see current status"

    join_template = jinja_env.get_template("join_race.jinja2")
    return join_template.render(
        race_id=actual_race_id,
        player_id=player_id,
        is_host=is_host,
        state=state_text,
    )


@mcp.tool()
async def start_race(race_id: str) -> str:
    """Start the race (lobby host only).

    This begins a 60-second planning phase before racing starts.
    During planning, you can set your initial speed and study the track.

    Args:
        race_id: The race/lobby ID

    Returns:
        Updated state with countdown information.
    """
    player_id = _get_player_id()

    data = await _backend_request(
        "POST",
        f"/lobbies/{race_id}/start",
        json={"player_id": player_id},
    )

    state = data["state"]
    state_text = _format_state_as_text(state, race_id, player_id)

    template = jinja_env.get_template("race_starting.jinja2")
    return template.render(race_id=race_id, player_id=player_id, state=state_text)


@mcp.tool()
async def get_state(race_id: str) -> str:
    """Get the current game state for your race.

    Args:
        race_id: The race ID returned from join_race

    Returns:
        Current game state including your position, speed, upcoming track, etc.
    """
    player_id = _get_player_id()

    data = await _backend_request("GET", f"/races/{race_id}/state")

    return _format_state_as_text(data["state"], race_id, player_id)


@mcp.tool()
async def find_race(ctx: Context) -> str:
    """Join public matchmaking to race against other players.

    This finds an open public lobby or creates a new one. You'll be matched
    with other players looking for a race.

    The race starts when EITHER:
    - All players send ready=True (via the control tool), OR
    - The lobby fills up (8 players), OR
    - 5 minutes pass (auto-start)

    After joining, use control(race_id, ready=True) to signal you're ready!

    Returns:
        Your assigned race_id and current matchmaking state.
    """
    player_id = _get_player_id()
    mcp_client = await _get_mcp_client(ctx)

    data = await _backend_request(
        "POST",
        "/matchmaking/join",
        json={"player_id": player_id, "mcp_client": mcp_client},
    )

    race_id = data["race_id"]
    state = data.get("state")
    created = data.get("created", False)

    if state:
        state_text = _format_state_as_text(state, race_id, player_id)
    else:
        state_text = "Joined matchmaking, use get_state to see current status"

    template = jinja_env.get_template("find_race.jinja2")
    return template.render(
        race_id=race_id,
        player_id=player_id,
        created=created,
        state=state_text,
    )


@mcp.tool()
async def control(
    race_id: str,
    target_speed: Optional[int] = None,
    drift: bool = False,
    use_item: bool = False,
    ready: bool = False,
) -> str:
    """Send control inputs for your kart.

    Args:
        race_id: The race ID returned from join_race or find_race
        target_speed: Set desired speed 0-3. Your kart automatically accelerates
                     (+1/tick) or brakes (up to -2/tick) toward this speed.
        drift: Set to True to enable drift mode. Must be in drift zone
               (2 tiles before a turn). Drift lets you take turns at speed 2.
        use_item: Set to True to use your held item (if any).
        ready: Set to True during MATCHMAKING phase to signal you're ready to start.
               IMPORTANT: Only use ready=True if your user EXPLICITLY asks you to
               ready up. Do NOT send this proactively - let users decide when to start.

    Returns:
        Updated game state after applying your input.

    Tips:
        - On straightaways: set target_speed=3
        - Before turns (tiles 7, 15, 29, 37): either brake to speed 1 OR enable drift
        - Drift zones are 3 tiles before each turn - watch for the notification!
        - With drift enabled, you can take turns at speed 2
        - Without drift, you must be at speed 1 to navigate turns safely
        - Speed 3+ will crash on turns even with drift enabled
        - Item boxes give you speed boosts - use them on straightaways ONLY!
    """
    player_id = _get_player_id()

    data = await _backend_request(
        "POST",
        f"/races/{race_id}/input",
        json={
            "player_id": player_id,
            "target_speed": target_speed,
            "drift": drift,
            "use_item": use_item,
            "ready": ready,
        },
    )

    return _format_state_as_text(data["state"], race_id, player_id)


