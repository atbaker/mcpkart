def create_auth_provider() -> Optional[HybridGitHubProvider]:
    """Create HybridGitHubProvider with GitHub OAuth and NPC dynamic token support.

    NPC tokens are dynamically generated by the backend and validated there.
    This provider just needs to recognize the npc- prefix and pass through.
    """
    has_github = GITHUB_CLIENT_ID and GITHUB_CLIENT_SECRET

    if not has_github:
        print("WARNING: GitHub OAuth not configured - NPC tokens only mode")
        # Still create provider so NPC tokens can pass through

    # Configure client storage with optional encryption
    client_storage = None
    if STORAGE_ENCRYPTION_KEY:
        from key_value.aio.wrappers.encryption import FernetEncryptionWrapper

        client_storage = FernetEncryptionWrapper(
            key_value=RedisStore(host=REDIS_HOST, port=REDIS_PORT),
            fernet=Fernet(STORAGE_ENCRYPTION_KEY.encode()),
        )
    elif REDIS_HOST:
        # Use Redis without encryption (dev mode)
        client_storage = RedisStore(host=REDIS_HOST, port=REDIS_PORT)

    provider = HybridGitHubProvider(
        client_id=GITHUB_CLIENT_ID or "npc-only-server",
        client_secret=GITHUB_CLIENT_SECRET or "npc-only-server-secret",
        base_url=MCP_BASE_URL,
        jwt_signing_key=JWT_SIGNING_KEY,
        client_storage=client_storage,
        required_scopes=["user", "read:org"] if has_github else [],
    )

    print("NPC dynamic token support enabled (backend validates secrets)")
    if has_github:
        print("GitHub OAuth configured for human players")

    return provider


