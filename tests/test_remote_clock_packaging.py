import hashlib
import json
import tarfile
from pathlib import Path

import pytest

from mcpkart.bench import reference_durations
from scripts import package_remote_clock as packaging


@pytest.fixture
def fresh_source(tmp_path):
    """Model a fresh checkout with source files, never local experiment inputs."""
    root = tmp_path / "checkout"
    for relative, content in packaging.selected_files(packaging.ROOT).items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    assert not (root / "artifacts").exists()
    return root


@pytest.mark.parametrize("engine", ["python", "rust"])
def test_package_uses_versioned_inputs_without_local_artifacts(fresh_source, tmp_path, engine):
    # Secrets and generated outputs must stay outside the allowlisted archive.
    (fresh_source / ".env").write_text("OPENROUTER_API_KEY=not-a-real-key\n")
    (fresh_source / "src/.env.local").write_text("not-a-real-secret\n")
    generated = fresh_source / "scripts/__pycache__/generated.pyc"
    generated.parent.mkdir()
    generated.write_bytes(b"generated bytecode")
    output = tmp_path / f"{engine}.tar.gz"
    report = packaging.package(fresh_source, output, engine)
    assert report["engine"] == engine
    assert report["expected_clock_mode"] == packaging.CLOCK_MODES[engine]
    assert abs(report["reference_s"] - 56.7) < 1e-6
    assert abs(report["long_clock_s"] - 170.1) < 1e-6

    with tarfile.open(output) as archive:
        contents = {}
        for entry in archive.getmembers():
            assert entry.isfile() and not entry.name.startswith("/")
            name = entry.name.removeprefix(packaging.ARCHIVE_ROOT + "/")
            assert not any(part.startswith(".env") or part in packaging.EXCLUDED_COMPONENTS
                           for part in Path(name).parts)
            contents[name] = archive.extractfile(entry).read()
    manifest = json.loads(contents.pop("PACKAGE-MANIFEST.json"))
    assert manifest["model_requests"] == 0
    assert set(contents) == set(manifest["files"])
    for name, content in contents.items():
        assert hashlib.sha256(content).hexdigest() == manifest["files"][name]["sha256"]
    for name, source in packaging.HELPERS.items():
        metadata = manifest["helper_sources"][name]
        assert metadata["source"] == source and not source.startswith("artifacts/")
        assert metadata["source_sha256"] == hashlib.sha256((fresh_source / source).read_bytes()).hexdigest()
    for name in ("run_controls.py", "long_clock.py", "environment.py"):
        helper = contents[f"remote-clock/{name}"].decode()
        compile(helper, name, "exec")
        assert f"info.get('engine', 'python') == '{engine}'" in helper
        assert packaging.CLOCK_MODES[engine] in helper
        assert "artifacts/rust-clock-v1/" not in helper


def test_frozen_reference_matches_current_physics_and_original_helper_hashes():
    directory = packaging.ROOT / "scripts/clock_helpers"
    provenance = json.loads((directory / "PROVENANCE.json").read_text())
    for name, metadata in provenance["helpers"].items():
        assert hashlib.sha256((directory / name).read_bytes()).hexdigest() == metadata["sha256"]
    assert hashlib.sha256((directory / "reference.json").read_bytes()).hexdigest() == (
        provenance["reference"]["sha256"]
    )
    durations = reference_durations(directory / "reference.json")
    assert set(durations) == {0} and abs(durations[0] - 56.7) < 1e-6


def test_package_refuses_symlink_source(fresh_source, tmp_path):
    (fresh_source / "scripts/untrusted.py").symlink_to(tmp_path / "external.py")
    with pytest.raises(ValueError, match="source symlink"):
        packaging.package(fresh_source, tmp_path / "bundle.tar.gz", "python")


def test_package_refuses_overwrite_without_changing_existing_archive(fresh_source, tmp_path):
    output = tmp_path / "bundle.tar.gz"
    output.write_bytes(b"existing evidence")
    with pytest.raises(ValueError, match="overwrite"):
        packaging.package(fresh_source, output, "python")
    assert output.read_bytes() == b"existing evidence"


@pytest.mark.parametrize("engine", ["python", "rust"])
def test_prepare_direct_controls_uses_fresh_output_and_safe_literal_paths(fresh_source, tmp_path, engine):
    output = tmp_path / "clock controls' evidence"
    report = packaging.prepare_validation(fresh_source, output, engine)
    assert report["model_requests"] == 0
    assert report["expected_clock_mode"] == packaging.CLOCK_MODES[engine]
    controls = (output / "run_controls.py").read_text()
    for name in ("run_controls.py", "long_clock.py", "environment.py"):
        compile((output / name).read_text(), name, "exec")
    assert repr(str(output.resolve() / "reference.json")) in controls
    assert repr(str(output.resolve() / "controls")) in controls
    assert "artifacts/rust-clock-v1/" not in controls
    assert reference_durations(output / "reference.json") == reference_durations(
        fresh_source / "scripts/clock_helpers/reference.json"
    )
    with pytest.raises(ValueError, match="overwrite validation directory"):
        packaging.prepare_validation(fresh_source, output, engine)
